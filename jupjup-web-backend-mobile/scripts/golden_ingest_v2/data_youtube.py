def vtt(name: str, lines: list[str], seconds: int = 7) -> dict[str, object]:
    """자막 줄 목록을 고정 간격 WEBVTT fixture로 만든다."""
    cues = ["WEBVTT", ""]
    for index, line in enumerate(lines):
        start, end = index * seconds, (index + 1) * seconds
        cues.append(f"{_ts(start)} --> {_ts(end)}")
        cues.append(line)
        cues.append("")
    return {"kind": "youtube", "name": f"transcripts/{name}.vtt", "body": "\n".join(cues)}


def _ts(seconds: int) -> str:
    return f"{seconds // 3600:02d}:{seconds % 3600 // 60:02d}:{seconds % 60:02d}.000"



def html_fixture(name: str, doc: tuple[str, list[str]]) -> dict[str, Any]:
    title, paragraphs = doc
    body = "".join(f"<p>{html.escape(paragraph)}</p>\n" for paragraph in paragraphs)
    page = (
        '<!doctype html>\n<html lang="ko"><head><meta charset="utf-8">'
        f"<title>{html.escape(title)}</title></head>\n<body><article>\n<h1>{html.escape(title)}</h1>\n"
        f"{body}</article></body></html>\n"
    )
    text_length = sum(len(paragraph) for paragraph in paragraphs)
    assert text_length > MIN_LONG_CHARS, (name, text_length)
    return {"kind": "url", "name": f"html/{name}.html", "body": page}


_DIGIT_HAS_FINAL = {
    "0": True,
    "1": True,
    "2": False,
    "3": True,
    "4": False,
    "5": False,
    "6": True,
    "7": True,
    "8": True,
    "9": False,
}
_JOSA = {"을": ("을", "를"), "이": ("이", "가"), "은": ("은", "는"), "와": ("과", "와"), "이었다": ("이었다", "였다")}


def _final(word: str) -> tuple[bool, bool]:
    """(받침 있음, 받침이 ㄹ)."""
    last = word.rstrip()[-1:] if word.strip() else ""
    if "가" <= last <= "힣":
        jong = (ord(last) - 0xAC00) % 28
        return jong != 0, jong == 8
    if last in _DIGIT_HAS_FINAL:
        return _DIGIT_HAS_FINAL[last], last in "178"
    return False, False


def j(word: str, particle: str) -> str:
    """조사를 받침에 맞춰 붙인다: j("누리대학교", "을") -> "누리대학교를"."""
    has_final, rieul = _final(word)
    if particle == "으로":
        return word + ("으로" if has_final and not rieul else "로")
    with_final, without_final = _JOSA[particle]
    return word + (with_final if has_final else without_final)


class _KoreanFormatter(string.Formatter):
    def format_field(self, value: Any, format_spec: str) -> str:
        if format_spec in _JOSA or format_spec == "으로":
            return j(str(value), format_spec)
        return super().format_field(value, format_spec)


_FORMATTER = _KoreanFormatter()


def _pick(rng: random.Random, frames: list[str], **values: Any) -> str:
    """frames 중 하나를 골라 채운다. ``{v:을}``처럼 쓰면 받침에 맞는 조사를 붙인다."""
    return _FORMATTER.format(rng.choice(frames), **values)


